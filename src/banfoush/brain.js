const AR_DIGITS = "٠١٢٣٤٥٦٧٨٩";
export function normalize(text) {
  return String(text || "")
    .toLowerCase()
    .replace(/[ً-ٰٟـ]/g, "") // تشكيل وتطويل
    .replace(/[أإآ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    .replace(/ؤ/g, "و")
    .replace(/ئ/g, "ي")
    .replace(/[٠-٩]/g, (d) => String(AR_DIGITS.indexOf(d)))
    .replace(/[^\p{L}\p{N}\s]/gu, " ")
    .replace(/\s+/g, " ")
    .trim();
}
/*
 * مطابقة كلمات: العبارات (أكثر من كلمة) تُبحث كما هي، والكلمة المفردة
 * تُطابق بداية كلمة في النص بعد نزع السوابق (ال، ب، و، ف، ل...) حتى لا
 * تُلتقط "عين" من "معين" ولا "خل" من "خلية". الكلمات القصيرة (حرفان)
 * يجب أن تطابق تماماً.
 */
const PREFIX = /^(وال|بال|فال|كال|لل|ال|و|ف|ب|ل|ك)/;
function has(t, keys) {
  const words = t.split(" ");
  return keys.some((k) => {
    const n = normalize(k);
    if (!n) return false;
    if (n.includes(" ")) return t.includes(n);
    return words.some((w) => {
      const bare = w.replace(PREFIX, "");
      return n.length <= 2 ? w === n || bare === n : w.startsWith(n) || bare.startsWith(n);
    });
  });
}
const rot = {};
function pick(id, list) {
  rot[id] = ((rot[id] ?? -1) + 1) % list.length;
  return list[rot[id]];
}
const greeting = () => {
  const h = new Date().getHours();
  return h < 12 ? "صباح الخير" : "مسا الخير";
};
const nm = (name) => (name ? ` يا ${name}` : "");

export function topicOf(t) {
  for (const k of ORDER) if (has(t, EXP[k].keys)) return k;
  return null;
}
export function suggest(visited = [], not) {
  return ORDER.find((k) => !visited.includes(k) && k !== not) || ORDER.find((k) => k !== not) || ORDER[0];
}
export function nextAfter(key, visited = []) {
  const i = ORDER.indexOf(key);
  for (let j = 1; j <= ORDER.length; j++) {
    const k = ORDER[(i + j) % ORDER.length];
    if (!visited.includes(k)) return k;
  }
  return ORDER[(i + 1) % ORDER.length];
}

